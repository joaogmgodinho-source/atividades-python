#  Leia três números diferentes e mostre qual deles é o maior

# Pede o primeiro número
n1 = int(input("Digite o primeiro número: "))

# Pede o segundo número
n2 = int(input("Digite o segundo número: "))

# Pede o terceiro número
n3 = int(input("Digite o terceiro número: "))

# Compara se o primero número é maior que o resto
if n1 > n2 and n1 > n2:
    print(f"{n1} é o maior")
# Compara se o segundo número é maior que o resto
elif n2 > n1 and n2 > n3:
    print(f"{n2} é maior")
# Compara se o terceiro número é maior que o resto
elif n3 > n1 and n3 > n2:
    print(f"{n3} é maior")